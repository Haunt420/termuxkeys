package com.example.engine

import com.example.model.KeyItem
import com.example.model.KeyPopup

object PropertiesFormatterEngine {

    /**
     * Generates a clean, valid `termux.properties` configuration string for extra-keys.
     */
    fun formatTermuxProperties(
        rows: List<List<KeyItem>>,
        style: String = "default"
    ): String {
        val sb = StringBuilder()
        sb.append("# ─────────────────────────────────────────────────────────────\n")
        sb.append("# Termux Extra Keys Configuration\n")
        sb.append("# Generated by TermuxKeys Studio\n")
        sb.append("# Place this file in ~/.termux/termux.properties\n")
        sb.append("# Reload active session: termux-reload-settings\n")
        sb.append("# ─────────────────────────────────────────────────────────────\n\n")

        sb.append("extra-keys-style = ").append(style).append("\n\n")

        if (rows.isEmpty()) {
            sb.append("extra-keys = []\n")
            return sb.toString()
        }

        sb.append("extra-keys = [ \\\n")
        for ((rowIndex, row) in rows.withIndex()) {
            sb.append("  [")
            for ((keyIndex, item) in row.withIndex()) {
                sb.append(formatKeyItem(item))
                if (keyIndex < row.size - 1) {
                    sb.append(", ")
                }
            }
            sb.append("]")
            if (rowIndex < rows.size - 1) {
                sb.append(", \\\n")
            } else {
                sb.append(" \\\n")
            }
        }
        sb.append("]\n")

        return sb.toString()
    }

    /**
     * Formats an individual KeyItem into Termux properties syntax.
     */
    private fun formatKeyItem(item: KeyItem): String {
        val hasDisplay = item.display.isNotBlank() && item.display != item.key
        val hasPopup = item.popup != null && item.popup.key.isNotBlank()

        // Simple string key format if no custom display and no popup
        if (!hasDisplay && !hasPopup) {
            return escapeAndQuote(item.key)
        }

        // Object notation: {key: '...', display: '...', popup: ...}
        val parts = mutableListOf<String>()
        parts.add("key: ${escapeAndQuote(item.key)}")

        if (hasDisplay) {
            parts.add("display: ${escapeAndQuote(item.display)}")
        }

        if (hasPopup) {
            val popup = item.popup!!
            val popupHasDisplay = popup.display.isNotBlank() && popup.display != popup.key
            if (!popupHasDisplay) {
                parts.add("popup: ${escapeAndQuote(popup.key)}")
            } else {
                parts.add("popup: {macro: ${escapeAndQuote(popup.key)}, display: ${escapeAndQuote(popup.display)}}")
            }
        }

        return "{${parts.joinToString(", ")}}"
    }

    private fun escapeAndQuote(str: String): String {
        val escaped = str.replace("\\", "\\\\").replace("'", "\\'")
        return "'$escaped'"
    }

    /**
     * Generates a ready-to-run 1-tap shell command for Termux terminal.
     */
    fun generateRunnableBashCommand(
        rows: List<List<KeyItem>>,
        style: String = "default"
    ): String {
        val properties = formatTermuxProperties(rows, style)
        return """
mkdir -p ~/.termux && cat << 'EOF' > ~/.termux/termux.properties
$properties
EOF
termux-reload-settings
echo "Extra keys updated and reloaded successfully!"
        """.trimIndent()
    }

    /**
     * Generates a single-line command for quick copying and running in Termux.
     */
    fun generateCompactBashOneLiner(rows: List<List<KeyItem>>, style: String = "default"): String {
        val propertiesContent = formatTermuxProperties(rows, style)
            .lines()
            .filter { !it.startsWith("#") && it.isNotBlank() }
            .joinToString("\n")
        
        return "mkdir -p ~/.termux && printf '%s\\n' \"$propertiesContent\" > ~/.termux/termux.properties && termux-reload-settings"
    }
}
